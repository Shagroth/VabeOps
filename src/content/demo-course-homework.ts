export function getHomeworkAssignment(moduleNumber: number) {
  return HOMEWORK_ASSIGNMENTS.find((assignment) => assignment.moduleNumber === moduleNumber);
}

export function formatHomeworkTime(range: [number, number]) {
  const format = (minutes: number) => (minutes / 60).toLocaleString("ru-RU", { maximumFractionDigits: 1 });
  return `${format(range[0])}–${format(range[1])} ч`;
}
